#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_clean() {
        assert!(EMOJI.len() >= 100);
        assert!(EMOJI.iter().all(|(e, words)| !e.is_empty() && !words.is_empty()));
        assert!(KAOMOJI.iter().all(|k| !k.contains('\t')));
        let mut seen = std::collections::HashSet::new();
        assert!(SYMBOLS.iter().all(|s| seen.insert(*s)), "duplicate symbol");
    }
}
